# Performs the parse version id helper step.
def parse_version_id(path, suffix=""):
    prefix = f"{API_BASE}/versions/"
    if not path.startswith(prefix):
        return None
    tail = path[len(prefix):]
    if suffix:
        if not tail.endswith(suffix):
            return None
        tail = tail[:-len(suffix)]
    if "/" in tail or not tail:
        return None
    try:
        return int(tail)
    except ValueError:
        return None


# Reads load current news json text from the current store or request context.
def load_current_news_json_text():
    if not NEWS_JSON_FILE.exists():
        return ""
    raw_text = NEWS_JSON_FILE.read_text(encoding="utf-8")
    try:
        raw = json.loads(raw_text)
    except Exception:
        return raw_text
    return json.dumps(canonical_newsletter_payload(raw), ensure_ascii=False, indent=2)


def requested_version_title_from_news(content_text):
    try:
        payload = json.loads(content_text)
    except Exception:
        return ""
    metadata = payload.get("metadata") if isinstance(payload, dict) else {}
    if not isinstance(metadata, dict):
        return ""
    return str(metadata.get("requested_version_title") or "").strip()


# Performs the version title from news helper step.
def version_title_from_news(content_text):
    try:
        payload = json.loads(content_text)
    except Exception:
        payload = {}
    template = payload.get("template") if isinstance(payload.get("template"), dict) else {}
    settings = load_newsletter_settings()
    issue_number = safe_int(
        template.get("issue_number") or settings.get("issue_number"),
        settings.get("issue_number") or 1,
    )
    month_year = str(
        template.get("month_year")
        or template.get("month_year_override")
        or settings.get("month_year_override")
        or ""
    ).strip()
    if not month_year:
        month_year = newsletter_template_from_settings(settings).get("month_year", "")
    title = f"نشرة الذكاء الاصطناعي الإصدار {issue_number} — {month_year}".strip()
    return issue_number, title


def normalize_version_title(value: str) -> str:
    """Normalize visible whitespace without changing the user's title."""
    return re.sub(r"\s+", " ", str(value or "")).strip()


def version_title_exists(connection, requested_title: str, exclude_id: int | None = None) -> bool:
    """Return whether another saved version already uses this title."""
    title = normalize_version_title(requested_title)
    if not title:
        return False
    query = "SELECT 1 FROM versions WHERE LOWER(BTRIM(title)) = LOWER(BTRIM(%s))"
    values: list[object] = [title]
    if exclude_id is not None:
        query += " AND id <> %s"
        values.append(int(exclude_id))
    query += " LIMIT 1"
    with connection.cursor() as cur:
        cur.execute(query, tuple(values))
        return cur.fetchone() is not None


def enforce_unique_version_titles() -> None:
    """Deduplicate legacy titles once, then enforce uniqueness in PostgreSQL."""
    global _VERSION_TITLE_UNIQUENESS_ENFORCED
    if _VERSION_TITLE_UNIQUENESS_ENFORCED:
        return
    con = versions_db()
    try:
        with con.cursor() as cur:
            cur.execute(
                "SELECT id, title FROM versions "
                "WHERE BTRIM(COALESCE(title, '')) <> '' ORDER BY id"
            )
            rows = cur.fetchall()

        updates = legacy_unique_title_updates(rows)

        with con.cursor() as cur:
            if updates:
                cur.executemany(
                    "UPDATE versions SET title = %s WHERE id = %s",
                    updates,
                )
            cur.execute(
                """
                CREATE UNIQUE INDEX IF NOT EXISTS versions_title_unique_ci
                ON versions ((LOWER(BTRIM(title))))
                WHERE BTRIM(COALESCE(title, '')) <> ''
                """
            )
        con.commit()
        _VERSION_TITLE_UNIQUENESS_ENFORCED = True
        if updates:
            trace(f"Renamed {len(updates)} legacy duplicate version title(s)")
    except Exception:
        con.rollback()
        raise
    finally:
        con.close()


def legacy_unique_title_updates(rows) -> list[tuple[str, int]]:
    """Return deterministic rename operations for duplicate historical rows."""
    used: set[str] = set()
    updates: list[tuple[str, int]] = []
    for version_id, raw_title in rows:
        base = normalize_version_title(raw_title)
        candidate = base
        suffix = 2
        while candidate.casefold() in used:
            candidate = f"{base} ({suffix})"
            suffix += 1
        used.add(candidate.casefold())
        if candidate != str(raw_title or ""):
            updates.append((candidate, int(version_id)))
    return updates
