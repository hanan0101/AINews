# Performs the enrich imported pdf payload from urls helper step.
def enrich_imported_pdf_payload_from_urls(payload):
    if not isinstance(payload, dict):
        return payload
    cards = []
    for section in ("items", "backup_news", "courses"):
        for item in payload.get(section) or []:
            if isinstance(item, dict) and item.get("url") and item.get("url") != "#":
                cards.append(item)
    if not cards:
        return payload
    url_to_cards = {}
    for card in cards:
        url_to_cards.setdefault(card.get("url"), []).append(card)
    metadata_by_url = {}
    with ThreadPoolExecutor(max_workers=min(6, max(1, len(url_to_cards)))) as executor:
        future_map = {executor.submit(fetch_url_metadata, url): url for url in url_to_cards}
        for future in as_completed(future_map):
            url = future_map[future]
            try:
                metadata_by_url[url] = future.result()
            except Exception as exc:
                metadata_by_url[url] = {"url": url, "title": "", "description": "", "error": str(exc)[:160]}
    enriched = 0
    for url, linked_cards in url_to_cards.items():
        metadata = metadata_by_url.get(url) or {}
        title = clean_web_meta_text(metadata.get("title") or "")
        description = clean_web_meta_text(metadata.get("description") or "")
        for card in linked_cards:
            if title and pdf_text_needs_url_metadata(card.get("title")):
                card["title"] = title
            if description and pdf_text_needs_url_metadata(card.get("text")):
                card["text"] = description
            if title or description:
                card["pdf_import_metadata"] = {
                    "title": title,
                    "description": description,
                    "source": "url_metadata",
                    "error": metadata.get("error") or "",
                }
                enriched += 1
    metadata = payload.get("metadata") if isinstance(payload.get("metadata"), dict) else {}
    metadata["pdf_url_metadata_enriched"] = enriched
    metadata["pdf_url_metadata_attempted"] = len(url_to_cards)
    payload["metadata"] = metadata
    trace(f"PDF import URL metadata enriched={enriched}/{len(url_to_cards)}")
    return payload


