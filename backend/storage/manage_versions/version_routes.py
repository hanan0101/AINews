# PDF BYTEA change: preserve the existing helper name but store PDF bytes in
# PostgreSQL instead of writing a local file. pdf_path is explicitly cleared
# because it is deprecated after the legacy-file migration.
def save_pdf_version_file(version_id: int, pdf_bytes: bytes, filename: str = "", connection=None) -> int:
    owns_connection = connection is None
    con = connection or versions_db()
    try:
        with con.cursor() as cur:
            cur.execute(
                "UPDATE versions SET pdf_data = %s, pdf_path = NULL WHERE id = %s",
                (psycopg2.Binary(pdf_bytes or b""), version_id),
            )
            updated = cur.rowcount
        if owns_connection:
            con.commit()
        return updated
    except Exception:
        if owns_connection:
            con.rollback()
        raise
    finally:
        if owns_connection:
            con.close()


