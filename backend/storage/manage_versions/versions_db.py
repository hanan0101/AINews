def init_versions_db():
    con = versions_db()
    try:
        with con.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS versions (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    issue_number INTEGER,
                    title TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    content TEXT,
                    kind TEXT DEFAULT 'json',
                    -- PDF BYTEA change: pdf_path is deprecated and remains only
                    -- long enough to migrate legacy files into pdf_data.
                    pdf_path TEXT,
                    original_filename TEXT,
                    pdf_data BYTEA,
                    hidden_from_users BOOLEAN DEFAULT FALSE
                )
            """)
            cur.execute("ALTER TABLE versions ADD COLUMN IF NOT EXISTS kind TEXT DEFAULT 'json'")
            cur.execute("ALTER TABLE versions ADD COLUMN IF NOT EXISTS pdf_path TEXT")
            cur.execute("ALTER TABLE versions ADD COLUMN IF NOT EXISTS original_filename TEXT")
            # PDF BYTEA change: add binary storage without changing existing JSON rows.
            cur.execute("ALTER TABLE versions ADD COLUMN IF NOT EXISTS pdf_data BYTEA")
            cur.execute("ALTER TABLE versions ADD COLUMN IF NOT EXISTS hidden_from_users BOOLEAN DEFAULT FALSE")
        con.commit()
    finally:
        con.close()
    seed_versions_from_sqlite_if_empty()
    migrate_json_versions_to_canonical_schema()
    enforce_unique_version_titles()


def migrate_json_versions_to_canonical_schema():
    """One-time runtime migration for old/manual JSON version snapshots."""
    global _JSON_VERSIONS_CANONICALIZED
    if _JSON_VERSIONS_CANONICALIZED:
        return
    con = versions_db()
    migrated = 0
    try:
        with con.cursor() as cur:
            cur.execute(
                "SELECT id, title, content FROM versions "
                "WHERE COALESCE(kind, 'json') = 'json'"
            )
            rows = cur.fetchall()
        with con.cursor() as cur:
            for version_id, current_title, content in rows:
                try:
                    raw = json.loads(content or "{}")
                    canonical = canonical_newsletter_payload(raw)
                except Exception as exc:
                    trace(f"Version {version_id} canonical migration skipped: {exc}")
                    continue
                canonical_text = json.dumps(canonical, ensure_ascii=False, indent=2)
                metadata = canonical.get("metadata") if isinstance(canonical.get("metadata"), dict) else {}
                requested_title = str(metadata.get("requested_version_title") or "").strip()
                next_title = requested_title or str(current_title or "").strip()
                if canonical_text != str(content or "") or next_title != str(current_title or "").strip():
                    cur.execute(
                        "UPDATE versions SET title = %s, content = %s WHERE id = %s",
                        (next_title, canonical_text, version_id),
                    )
                    migrated += 1
        con.commit()
        _JSON_VERSIONS_CANONICALIZED = True
        if migrated:
            trace(f"Canonicalized {migrated} stored JSON newsletter versions")
    except Exception:
        con.rollback()
        raise
    finally:
        con.close()


# seeds/initial_versions.db ships with the historical starter versions, but a
# genuinely fresh PostgreSQL volume (first-time clone/
# setup, or a collaborator's machine) starts with an empty versions table -
# init_versions_db() only does CREATE TABLE IF NOT EXISTS, it never
# populates data. Without this, "previous versions" is silently empty on
# every fresh environment even though the repo has the history. Runs once:
# after the first successful seed the table is non-empty, so every later
# call is just a cheap COUNT(*) short-circuit.
SEED_VERSIONS_DB_FILE = Path(__file__).resolve().parent / "seeds" / "initial_versions.db"


def seed_versions_from_sqlite_if_empty():
    if not SEED_VERSIONS_DB_FILE.exists():
        return
    con = versions_db()
    try:
        with con.cursor() as cur:
            cur.execute("SELECT COUNT(*) FROM versions")
            (count,) = cur.fetchone()
        if count:
            return
        import sqlite3
        sconn = sqlite3.connect(str(SEED_VERSIONS_DB_FILE))
        try:
            rows = sconn.execute(
                "SELECT id, issue_number, title, created_at, content, kind, "
                "pdf_path, original_filename, pdf_data, hidden_from_users "
                "FROM versions ORDER BY id"
            ).fetchall()
        finally:
            sconn.close()
        if not rows:
            return
        with con.cursor() as cur:
            for row in rows:
                (vid, issue_number, title, created_at, content, kind,
                 pdf_path, original_filename, pdf_data, hidden) = row
                cur.execute(
                    """
                    INSERT INTO versions (id, issue_number, title, created_at, content,
                                           kind, pdf_path, original_filename, pdf_data, hidden_from_users)
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                    ON CONFLICT (id) DO NOTHING
                    """,
                    (
                        vid, issue_number, title, created_at, content, kind,
                        pdf_path, original_filename,
                        psycopg2.Binary(pdf_data) if pdf_data is not None else None,
                        bool(hidden),
                    ),
                )
            # Explicit ids bypass the identity sequence - advance it past the
            # seeded max so the next user-saved version doesn't collide.
            cur.execute(
                "SELECT setval(pg_get_serial_sequence('versions', 'id'), "
                "COALESCE((SELECT MAX(id) FROM versions), 1))"
            )
        con.commit()
        trace(f"Seeded {len(rows)} versions from {SEED_VERSIONS_DB_FILE} into empty PostgreSQL table")
    except Exception as exc:
        con.rollback()
        trace(f"Version seed from SQLite failed: {exc}")
    finally:
        con.close()


# PostgreSQL change: centralize psycopg2 connection creation for every existing
# version endpoint while keeping the calling functions and routes unchanged.
def versions_db():
    return postgres_connection()


