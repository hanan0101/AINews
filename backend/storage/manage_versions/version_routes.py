# Saves attach newsletter json to pdf to the configured output or state store.
def attach_newsletter_json_to_pdf(pdf_bytes, newsletter_payload):
    if not isinstance(newsletter_payload, dict) or not newsletter_payload.get("items"):
        return pdf_bytes
    try:
        from pypdf import PdfReader, PdfWriter
    except Exception as exc:
        trace(f"PDF JSON attachment skipped: pypdf unavailable: {exc}")
        return pdf_bytes
    try:
        reader = PdfReader(io.BytesIO(pdf_bytes))
        writer = PdfWriter()
        for page in reader.pages:
            writer.add_page(page)
        try:
            if reader.metadata:
                writer.add_metadata({str(k): str(v) for k, v in dict(reader.metadata).items() if v is not None})
        except Exception:
            pass
        payload = dict(newsletter_payload)
        metadata = payload.get("metadata") if isinstance(payload.get("metadata"), dict) else {}
        metadata.update({
            "embedded_in_pdf": True,
            "embedded_schema": "ainewsletter_version_v1",
            "embedded_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        })
        payload["metadata"] = metadata
        attachment_bytes = json.dumps(payload, ensure_ascii=False, indent=2).encode("utf-8")
        writer.add_attachment("ainewsletter-version.json", attachment_bytes)
        output = io.BytesIO()
        writer.write(output)
        trace(f"PDF export embedded JSON attachment bytes={len(attachment_bytes)}")
        return output.getvalue()
    except Exception as exc:
        trace(f"PDF JSON attachment failed: {exc}")
        return pdf_bytes


# Performs the extract embedded newsletter payload helper step.
def extract_embedded_newsletter_payload(pdf_bytes):
    try:
        from pypdf import PdfReader
    except Exception:
        return None
    try:
        reader = PdfReader(io.BytesIO(pdf_bytes))
        attachments = getattr(reader, "attachments", {}) or {}
    except Exception:
        return None
    candidates = []
    if isinstance(attachments, dict):
        for name, values in attachments.items():
            if not str(name).lower().endswith(".json"):
                continue
            if isinstance(values, (bytes, bytearray)):
                candidates.append((name, bytes(values)))
            else:
                for value in values or []:
                    if isinstance(value, (bytes, bytearray)):
                        candidates.append((name, bytes(value)))
    for name, raw in candidates:
        try:
            payload = json.loads(raw.decode("utf-8"))
        except Exception:
            continue
        if isinstance(payload, dict) and isinstance(payload.get("items"), list):
            trace(f"PDF import found embedded JSON attachment name={name} items={len(payload.get('items') or [])}")
            return payload
    return None


